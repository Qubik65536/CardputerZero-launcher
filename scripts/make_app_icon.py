def glyph_rows(char):
    code = ord(char)
    return GLYPHS[code - 32] if 32 <= code < 128 else GLYPHS[ord("?") - 32]


def inside_rounded_square(x, y, size, radius):
    cx = min(max(x, radius), size - 1 - radius)
    cy = min(max(y, radius), size - 1 - radius)
    return (x - cx) ** 2 + (y - cy) ** 2 <= radius ** 2


def render(text, size, color):
    red, green, blue = (color >> 16) & 0xFF, (color >> 8) & 0xFF, color & 0xFF
    pixels = [[(0, 0, 0, 0)] * size for _ in range(size)]
    radius = size // 5
    for y in range(size):
        # Slightly lighter towards the top for a bit of depth.
        shade = 1.0 + 0.25 * (1 - y / size)
        top = tuple(min(255, int(channel * shade)) for channel in (red, green, blue))
        for x in range(size):
            if inside_rounded_square(x, y, size, radius):
                pixels[y][x] = top + (255,)

    scale = max(1, (size * 3 // 4) // (8 * max(1, len(text))))
    scale = min(scale, size // 16 * 2 or 1)
    width, height = 8 * scale * len(text), 8 * scale
    left, top_edge = (size - width) // 2, (size - height) // 2
    for index, char in enumerate(text):
        for row, bits in enumerate(glyph_rows(char)):
            for column in range(8):
                if bits & (0x80 >> column):
                    for dy in range(scale):
                        for dx in range(scale):
                            x = left + (index * 8 + column) * scale + dx
                            y = top_edge + row * scale + dy
                            pixels[y][x] = (255, 255, 255, 255)
    return pixels


def png_bytes(pixels):
    height, width = len(pixels), len(pixels[0])
    raw = b"".join(b"\x00" + bytes(channel for pixel in row for channel in pixel) for row in pixels)

    def chunk(kind, data):
        body = kind + data
        return struct.pack(">I", len(data)) + body + struct.pack(">I", zlib.crc32(body) & 0xFFFFFFFF)

    header = struct.pack(">IIBBBBB", width, height, 8, 6, 0, 0, 0)  # 8-bit RGBA
    return b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", header) + chunk(b"IDAT", zlib.compress(raw, 9)) + chunk(b"IEND", b"")


def parse_args(argv):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("text", help="1-3 characters to draw, e.g. the app's initials")
    parser.add_argument("-o", "--output", type=Path, required=True, help="PNG file to write")
    parser.add_argument("--color", default="2E7D32", help="background color as RRGGBB hex (default 2E7D32)")
    parser.add_argument("--size", type=int, default=100, help="icon edge in pixels (default 100)")
    return parser.parse_args(argv)


def main(argv=None):
    args = parse_args(argv)
    text = args.text.strip()[:3] or "?"
    pixels = render(text, args.size, int(args.color.lstrip("#"), 16))
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_bytes(png_bytes(pixels))
    print(f"wrote {args.output} ({args.size}x{args.size})")


if __name__ == "__main__":
    main()
