   Turn a binary file into OCaml source, the way Rust's include_bytes! embeds
   one: `ocaml src/embed.ml FILE` prints `let data = "..."` to stdout.

   src/dune runs it at build time to make the module Wallpaper from
   src/wallpaper.rgb565. It is a script for the `ocaml` toplevel, not part of
   the app: src/dune leaves it out of the executable's modules. *)

let bytes_per_line = 32

let () =
  let data = In_channel.with_open_bin Sys.argv.(1) In_channel.input_all in
  print_string "(* Generated by src/embed.ml; do not edit. *)\n\nlet data =\n  \"";
  String.iteri
    (fun index byte ->
      if index mod bytes_per_line = 0 then print_string "\\\n   ";
      Printf.printf "\\x%02x" (Char.code byte))
    data;
  print_string "\"\n"
